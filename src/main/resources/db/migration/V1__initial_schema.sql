CREATE TABLE users
(
    userid UUID PRIMARY KEY,
    username VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(60) NOT NULL
);

CREATE SEQUENCE groups_groupid_seq
    START WITH 1
    INCREMENT BY 1;

CREATE TABLE groups
(
    groupid INTEGER NOT NULL DEFAULT nextval('groups_groupid_seq'),
    groupname VARCHAR(20) NOT NULL,
    userid UUID NOT NULL,

    CONSTRAINT pk_groups
        PRIMARY KEY (groupid),

    CONSTRAINT fk_groups_user
        FOREIGN KEY (userid)
        REFERENCES users(userid)
        ON DELETE CASCADE,

    CONSTRAINT uk_groups_user_name
        UNIQUE (userid, groupname)
);

ALTER SEQUENCE groups_groupid_seq
    OWNED BY groups.groupid;

CREATE INDEX idx_groups_userid
    ON groups(userid);

CREATE TABLE urls
(
    urlid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    longurl VARCHAR(2048) NOT NULL,
    shortcode VARCHAR(32) UNIQUE,
    created_date TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    userid UUID NOT NULL,

    CONSTRAINT fk_urls_user
        FOREIGN KEY (userid)
        REFERENCES users(userid)
        ON DELETE CASCADE
);

CREATE INDEX idx_urls_shortcode
    ON urls(shortcode);

CREATE INDEX idx_urls_userid
    ON urls(userid);
